# Compare two staged installations (DESTDIR) of OpenLDAP, typically one
# made with "make install" and one with "meson install", and report every
# difference in:
#
#  - the installed tree: file names, types, permissions, symlink targets;
#  - the contents of non-ELF files (headers, .pc, .la, man pages, config);
#  - ELF objects: SONAME, NEEDED, RPATH/RUNPATH, FLAGS, stripped or not,
#    exported (defined dynamic) symbols with their versions, undefined
#    dynamic symbols;
#  - static archives: member objects and defined global symbols;
#  - with abidiff (libabigail) installed, the ABI of shared libraries.
#
# Lines that only name the generator ("Generated from x.hin by configure"
# or "by meson", the libtool banner in .la files) are not compared, and
# archive members are compared by object name (foo.o, whatever the
# build system calls it).  See doc/method.txt for the rationale.
#
# With --build-tree DIR (may be repeated), RPATH/RUNPATH entries inside
# DIR are taken out of the comparison and listed as known differences:
# libtool leaves the build tree in the RUNPATH of programs installed
# with shared libraries only, which meson does not reproduce.
#
# usage: compare-install.sh [--build-tree DIR]... DESTDIR_A DESTDIR_B
# Exit status is 0 when no difference is found, 1 otherwise.

LC_ALL=C
export LC_ALL

BUILD_TREES=
while test $# -gt 0 ; do
	case "$1" in
	--build-tree)
		test $# -ge 2 || { echo "$0: --build-tree needs a directory" >&2; exit 2; }
		BUILD_TREES="$BUILD_TREES $2"
		shift 2 ;;
	--)	shift ; break ;;
	-*)	echo "$0: unknown option $1" >&2 ; exit 2 ;;
	*)	break ;;
	esac
done

if test $# -ne 2 || test ! -d "$1" || test ! -d "$2" ; then
	echo "usage: $0 [--build-tree DIR]... DESTDIR_A DESTDIR_B" >&2
	exit 2
fi
A=`cd "$1" && pwd`
B=`cd "$2" && pwd`

TMP=`mktemp -d "${TMPDIR:-/tmp}/compare-install.XXXXXX"` || exit 2
trap 'rm -rf "$TMP"' 0 1 2 15

status=0
section() {
	printf '\n=== %s\n' "$1"
}
# report DIFF-OUTPUT-FILE LABEL
report() {
	if test -s "$1" ; then
		status=1
		test -n "$2" && echo "--- $2"
		cat "$1"
	fi
}

tree() {
	(cd "$1" && find . -printf '%y %m %P -> %l\n' | sed 's/ -> $//' | sort)
}

section "installed tree (type mode path -> link)"
tree "$A" > "$TMP/tree.a"
tree "$B" > "$TMP/tree.b"
diff "$TMP/tree.a" "$TMP/tree.b" > "$TMP/d"
report "$TMP/d"

# regular files present in both trees
(cd "$A" && find . -type f | sort) > "$TMP/files.a"
(cd "$B" && find . -type f | sort) > "$TMP/files.b"
comm -12 "$TMP/files.a" "$TMP/files.b" > "$TMP/common"

is_elf() {
	test "`head -c 4 "$1" | od -An -c | tr -d ' '`" = '177ELF'
}
is_ar() {
	test "`head -c 7 "$1"`" = '!<arch>'
}
normalize() {
	sed -e '/^\/\* .* Generated from .* by \(configure\|meson\)\.  \*\/$/d' \
		-e '/^# Generated by \(libtool\|the OpenLDAP meson build\)/d' \
		-e '/^# Generated by libtool (GNU libtool)/d' "$1"
}
dynamic() {
	readelf -d "$1" 2>/dev/null |
		sed -n 's/^ *0x[0-9a-f]* *(\(NEEDED\|SONAME\|RPATH\|RUNPATH\|FLAGS\|FLAGS_1\|TEXTREL\|BIND_NOW\)) *\(.*\)$/\1 \2/p' |
		filter_rpath "$1"
}
# Drop the RPATH/RUNPATH entries inside the --build-tree directories,
# recording them in $TMP/known
filter_rpath() {
	awk -v trees="$BUILD_TREES" -v file="$1" -v known="$TMP/known" '
	BEGIN { nt = split(trees, t, " ") }
	/^(RPATH|RUNPATH) / && nt > 0 {
		tag = $1
		path = $0
		sub(/^[^[]*\[/, "", path); sub(/\]$/, "", path)
		n = split(path, p, ":")
		keep = ""
		for (i = 1; i <= n; i++) {
			inside = 0
			for (j = 1; j <= nt; j++)
				if (index(p[i], t[j]) == 1) inside = 1
			if (inside)
				print file ": " tag " " p[i] >> known
			else
				keep = keep (keep == "" ? "" : ":") p[i]
		}
		if (keep != "")
			print tag " Library " tolower(tag) ": [" keep "]"
		next
	}
	{ print }'
}
stripped() {
	if readelf -S "$1" 2>/dev/null | grep -q ' \.symtab ' ; then
		echo "symtab present"
	else
		echo "stripped"
	fi
}
exported() {
	nm -D --defined-only --with-symbol-versions "$1" 2>/dev/null |
		awk '{ print $2, $3 }' | sort
}
undefined() {
	nm -D --undefined-only --with-symbol-versions "$1" 2>/dev/null |
		awk '{ print $NF }' | sort
}
# meson names objects foo.c.o (meson-generated_.._foo.c.o for generated
# sources), libtool foo.o
members() {
	ar t "$1" | sed -e 's,.*/,,' -e 's/^meson-generated_[^_]*_//' \
		-e 's/\.c\.o$/.o/' | sort
}
archive_globals() {
	nm --defined-only "$1" 2>/dev/null |
		awk 'NF == 3 && $2 ~ /^[A-Z]$/ { print $2, $3 }' | sort
}

# cmpout LABEL FUNC FILE-A FILE-B
cmpout() {
	$2 "$3" > "$TMP/o.a"
	$2 "$4" > "$TMP/o.b"
	diff "$TMP/o.a" "$TMP/o.b" > "$TMP/o.d"
	report "$TMP/o.d" "$1"
}

section "file contents"
have_abidiff=no
command -v abidiff > /dev/null 2>&1 && have_abidiff=yes
while read f ; do
	a="$A/$f"
	b="$B/$f"
	if is_elf "$a" && is_elf "$b" ; then
		cmpout "$f: dynamic section" dynamic "$a" "$b"
		cmpout "$f: symbol table" stripped "$a" "$b"
		cmpout "$f: exported symbols" exported "$a" "$b"
		cmpout "$f: undefined symbols" undefined "$a" "$b"
		case "`readelf -h "$a" | sed -n 's/^ *Type: *\([A-Z]*\).*/\1/p'`" in
		DYN)
			if test $have_abidiff = yes && readelf -d "$a" | grep -q SONAME ; then
				abidiff "$a" "$b" > "$TMP/abi" 2>&1 ||
					report "$TMP/abi" "$f: abidiff"
			fi
			;;
		esac
	elif is_ar "$a" && is_ar "$b" ; then
		cmpout "$f: archive members" members "$a" "$b"
		cmpout "$f: archive global symbols" archive_globals "$a" "$b"
	else
		normalize "$a" > "$TMP/c.a"
		normalize "$b" > "$TMP/c.b"
		diff -u "$TMP/c.a" "$TMP/c.b" | sed '1,2d' > "$TMP/c.d"
		report "$TMP/c.d" "$f"
	fi
done < "$TMP/common"
test $have_abidiff = no && printf '\n(abidiff not found: ABI comparison skipped)\n'

if test -s "$TMP/known" ; then
	section "known differences (not counted): build tree in RPATH/RUNPATH"
	sed "s,^$A/,," "$TMP/known" | sed "s,^$B/,," | sort -u
fi

if test $status = 0 ; then
	printf '\nNo differences found.\n'
else
	printf '\nDifferences found.\n'
fi
exit $status
